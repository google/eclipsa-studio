import 'dart:convert';
import 'dart:io';

import 'package:flutter_test/flutter_test.dart';

/// Pins the shape of assets/third_party_notices.json — main.dart parses
/// it at startup to register engine licenses into the LicenseRegistry
/// (ES-57). Generated by scripts/collect_third_party_notices.py.
void main() {
  test('third_party_notices.json parses into named license entries', () {
    final raw = File('assets/third_party_notices.json').readAsStringSync();
    final components =
        (jsonDecode(raw) as Map<String, dynamic>)['components'] as List;

    expect(components, isNotEmpty);
    for (final c in components.cast<Map<String, dynamic>>()) {
      expect(c['name'], isA<String>());
      expect((c['name'] as String).trim(), isNotEmpty);
      expect(c['license'], isA<String>());
      expect((c['license'] as String).trim(), isNotEmpty);
      expect(c['text'], isA<String>());
      expect((c['text'] as String).trim(), isNotEmpty);
    }

    // The attribution that motivated ES-57 must be present.
    final names = components
        .cast<Map<String, dynamic>>()
        .map((c) => c['name'] as String)
        .toList();
    expect(names.any((n) => n.contains('FDK AAC')), isTrue);
  });
}
