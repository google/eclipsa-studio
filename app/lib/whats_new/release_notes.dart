import 'dart:convert';

import 'package:flutter/services.dart' show rootBundle;

import '../logging/log.dart';

/// One release entry as parsed from `assets/releases.json`. The JSON
/// is generated by `scripts/release_notes.py` from the public
/// `RELEASES.md` file at the repo root, so this model has to stay in
/// step with that script's output.
class ReleaseNotes {
  /// Semver string, e.g. `0.6.2`.
  final String version;

  /// ISO date (YYYY-MM-DD) when known, otherwise null.
  final String? date;

  /// Human-readable date, e.g. `May 4, 2026`.
  final String dateDisplay;

  /// All change bullets for the release, in document order. Generated by
  /// `release_notes.py` as a single list (the former Highlights and
  /// What's new sections merged — see ES-129).
  final List<String> notes;

  /// One-paragraph summary used by maintenance / placeholder releases
  /// that have no change bullets. Null when the release uses the
  /// structured form.
  final String? summary;

  const ReleaseNotes({
    required this.version,
    required this.date,
    required this.dateDisplay,
    required this.notes,
    required this.summary,
  });

  factory ReleaseNotes.fromJson(Map<String, dynamic> json) {
    return ReleaseNotes(
      version: json['version'] as String,
      date: json['date'] as String?,
      dateDisplay: json['date_display'] as String,
      notes: (json['notes'] as List<dynamic>? ?? const []).cast<String>(),
      summary: json['summary'] as String?,
    );
  }

  /// True when the release has no change bullets (a maintenance /
  /// placeholder release like 0.6.1).
  bool get isMaintenance => notes.isEmpty;
}

/// Loads `assets/releases.json` and returns the release entries in
/// file order (newest first). Returns an empty list when the asset
/// is missing or malformed — callers should treat that as "no notes
/// to show" rather than fail.
Future<List<ReleaseNotes>> loadReleaseNotes() async {
  String raw;
  try {
    raw = await rootBundle.loadString('assets/releases.json');
  } on Exception catch (e) {
    Log.w(LogCat.app, 'release notes asset missing or unreadable', e);
    return const [];
  }

  Map<String, dynamic> doc;
  try {
    doc = jsonDecode(raw) as Map<String, dynamic>;
  } on FormatException catch (e) {
    Log.e(LogCat.app, 'release notes JSON malformed', e);
    return const [];
  }

  final list = doc['releases'] as List<dynamic>? ?? const [];
  return list
      .cast<Map<String, dynamic>>()
      .map(ReleaseNotes.fromJson)
      .toList(growable: false);
}

/// Returns the [ReleaseNotes] entry for [version], or null if no
/// matching entry exists.
ReleaseNotes? findRelease(List<ReleaseNotes> releases, String version) {
  for (final r in releases) {
    if (r.version == version) return r;
  }
  return null;
}

/// Returns the entries newer than [sinceVersion] (exclusive), in the
/// same order as the input list (newest first). The list is assumed
/// to be ordered newest-first — the parser produces it that way from
/// RELEASES.md, where the file ordering is the source of truth.
///
/// Falls back to the full list when [sinceVersion] is not found, so
/// users on a build that predates a particular release see every
/// entry up to today rather than nothing.
List<ReleaseNotes> releasesSince(
  List<ReleaseNotes> releases,
  String sinceVersion,
) {
  final out = <ReleaseNotes>[];
  for (final r in releases) {
    if (r.version == sinceVersion) return out;
    out.add(r);
  }
  return out;
}
