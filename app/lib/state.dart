  advanced1(
    label: 'Advanced-1',
    profileIndex: 4,
    specVersion: IamfSpecVersion.v2_0,
    maxAudioElements: 18,
    maxChannels: 18,
    maxSubMixesPerMix: 2,
    maxCodecConfigs: 2,
    allowObjectBased: true,
    allowMixedTypes: true,
  ),
  advanced2(
    label: 'Advanced-2',
    profileIndex: 5,
    specVersion: IamfSpecVersion.v2_0,
    maxAudioElements: 28,
    maxChannels: 28,
    maxSubMixesPerMix: 2,
    maxCodecConfigs: 2,
    allowObjectBased: true,
    allowMixedTypes: true,
