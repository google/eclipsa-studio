/// Tab identifiers used by the workspace shell. `inspector` only
/// appears in Playback mode; `elements` / `mix` only in Creator.
/// `renderer` is shared across both.
abstract final class WorkspaceTabs {
  static const elements = 'elements';
  static const mix = 'mix';
  static const renderer = 'renderer';
  static const inspector = 'inspector';

  static const _creator = [elements, mix, renderer];
  static const _playback = [inspector, renderer];

  /// Ordered list of tabs that should be visible in [mode]. Returns
  /// empty when no workspace is loaded.
  static List<String> allowedIn(WorkspaceMode mode) => switch (mode) {
    WorkspaceMode.creator => _creator,
    WorkspaceMode.playback => _playback,
    WorkspaceMode.none => const [],
  };

  /// Tab a workspace lands on when [mode] is entered. Playback (QC)
  /// opens on the renderer — the QC task is auditioning the render;
  /// the inspector is reference detail. Other modes open on their
  /// first tab.
  static String defaultTab(WorkspaceMode mode) {
    if (mode == WorkspaceMode.playback) return renderer;
    final allowed = allowedIn(mode);
    return allowed.isEmpty ? elements : allowed.first;
  }
}

class ActiveTabNotifier extends Notifier<String> {
  @override
  String build() {
    // Keep the active tab in a mode that actually shows it. If the
    // mode changes and the current tab is no longer allowed, clamp to
    // the new mode's default tab. `renderer` is the only shared tab,
    // so the clamp only fires on Creator↔Playback transitions.
    ref.listen<WorkspaceMode>(workspaceModeProvider, (_, next) {
      final allowed = WorkspaceTabs.allowedIn(next);
      if (allowed.isEmpty) return;
      if (!allowed.contains(state)) {
        state = WorkspaceTabs.defaultTab(next);
      }
    });
    // Seed from the current mode rather than hard-coding `elements` —
    // when AppShell mounts after `enterPlayback()`, this notifier's
    // build() runs only after the mode flip, so the listener above
    // never sees that transition. Without this peek the playback
    // shell would render ElementsView (creator timeline) until the
    // user manually selected a tab.
    return WorkspaceTabs.defaultTab(ref.read(workspaceModeProvider));
  }

  void set(String v) => state = v;
}

class PlayingNotifier extends Notifier<bool> {
  @override
  bool build() => false;
  void set(bool v) => state = v;
  void toggle() => state = !state;

  /// Space-bar play/stop semantics, shared by every entry point that
  /// binds the key (main shell, video pop-out window, routing matrix
  /// screen — ES-79) so they can't drift: stop optionally returns the
  /// playhead to where playback started (returnOnStopProvider); start
  /// marks the play-start and re-enables timeline follow. Starting is
  /// swallowed while transport is blocked (transportBlockedProvider:
  /// the IAMF duration scan, or a Loudness Report pass or an ADM
  /// import holding the renderer) — the keyboard must not bypass the
  /// disabled transport controls — but stopping stays available so a
  /// transport that was already rolling can always be silenced.
  void toggleTransport() {
    if (state) {
      state = false;
      if (ref.read(returnOnStopProvider)) {
        ref.read(transportProvider.notifier).returnToPlayStart();
      }
    } else {
      if (ref.read(transportBlockedProvider)) return;
      ref.read(transportProvider.notifier).markPlayStart();
      ref.read(followOverrideProvider.notifier).set(false);
      state = true;
    }
  }
}

