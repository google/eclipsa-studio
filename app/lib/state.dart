class TimelineViewport {
  final double zoomLevel; // 1.0 = full, >1 = zoomed in
  final double scrollOffset; // 0–1 normalized
  final double trackScale; // vertical scale: 0.5–3.0

  const TimelineViewport({
    this.zoomLevel = 1.0,
    this.scrollOffset = 0.0,
    this.trackScale = 1.0,
  });

  TimelineViewport copyWith({
    double? zoomLevel,
    double? scrollOffset,
    double? trackScale,
  }) {
    return TimelineViewport(
      zoomLevel: zoomLevel ?? this.zoomLevel,
      scrollOffset: scrollOffset ?? this.scrollOffset,
      trackScale: trackScale ?? this.trackScale,
    );
  }
}

class TimelineViewportNotifier extends Notifier<TimelineViewport> {
  static const double _minZoom = 1.0;
  static const double _maxZoom = 500.0;

  @override
  TimelineViewport build() => const TimelineViewport();

  void setZoom(double zoom) {
    state = state.copyWith(zoomLevel: zoom.clamp(_minZoom, _maxZoom));
  }

  void setScroll(double scroll) {
    state = state.copyWith(scrollOffset: scroll.clamp(0.0, 1.0));
  }

  /// Zoom by [factor] while keeping the time at [pivotFrac] — a 0–1
  /// fraction of the *visible* window — at the same on-screen
  /// position. This is the anchor for pointer-centered zoom
  /// (trackpad pinch, modifier+wheel): the content under the cursor
  /// stays put while the window contracts or expands around it.
  void zoomAroundFraction(double factor, double pivotFrac) {
    final durationSec = ref.read(transportProvider).durationSeconds;
    final newZoom = (state.zoomLevel * factor).clamp(_minZoom, _maxZoom);
    if (durationSec <= 0) {
      state = state.copyWith(zoomLevel: newZoom, scrollOffset: 0.0);
      return;
    }
    final frac = pivotFrac.clamp(0.0, 1.0);
    final oldVisible = durationSec / state.zoomLevel;
    final oldStart = state.scrollOffset * (durationSec - oldVisible);
    final pivotTime = oldStart + frac * oldVisible;

    final newVisible = durationSec / newZoom;
    final newStart = pivotTime - frac * newVisible;
    final maxScrollable = durationSec - newVisible;
    final newScroll = maxScrollable > 0
        ? (newStart / maxScrollable).clamp(0.0, 1.0)
        : 0.0;

    state = state.copyWith(zoomLevel: newZoom, scrollOffset: newScroll);
  }

  /// Zoom by [factor] while keeping the playhead's pixel position fixed.
  /// Falls back to the viewport center when the playhead is off-screen,
  /// so the user's current view stays put. Reads the playhead and
  /// session duration from [transportProvider] directly to keep the
  /// callsites trivial.
  void zoomByAroundPlayhead(double factor) {
    final transport = ref.read(transportProvider);
    final durationSec = transport.durationSeconds;
    if (durationSec <= 0) {
      zoomAroundFraction(factor, 0.0);
      return;
    }
    final oldVisible = durationSec / state.zoomLevel;
    final oldStart = state.scrollOffset * (durationSec - oldVisible);
    final playheadSec = transport.seconds;
    final onScreen =
        playheadSec >= oldStart && playheadSec <= oldStart + oldVisible;
    final pivotFrac = onScreen ? (playheadSec - oldStart) / oldVisible : 0.5;
    zoomAroundFraction(factor, pivotFrac);
  }

  void scrollBy(double delta) {
    state = state.copyWith(
      scrollOffset: (state.scrollOffset + delta).clamp(0.0, 1.0),
    );
  }

  void setTrackScale(double scale) {
    state = state.copyWith(trackScale: scale.clamp(0.5, 3.0));
  }

  void scaleTracksBy(double factor) {
    state = state.copyWith(
      trackScale: (state.trackScale * factor).clamp(0.5, 3.0),
    );
  }
}

