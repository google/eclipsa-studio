/// Map an AudioElement's type string + layout to OAR parameters.
/// Returns (type, subType, channels) for eclipsa_studio_element_set_type().
(int, int, int) elementToOarType(AudioElement el) {
  final type = el.type.toLowerCase();

  if (type.contains('object')) {
    // Object-based: subType = num_objects (1 or 2).
    return (2, el.isDual ? 2 : 1, el.isDual ? 2 : 1);
  }

  if (type.contains('scene')) {
    // Scene-based: subType = oar_hoa_t (0=ZOA, 1=1OA, 2=2OA, 3=3OA, 4=4OA).
    return (1, el.ambisonicsOrder, _ambisonicsChannels(el.ambisonicsOrder));
  }

  // Channel-based: subType = oar_layout_t.
  final layout = el.layout.toLowerCase();
  final (oarLayout, channels) = _layoutToOar(layout);
  return (0, oarLayout, channels);
}

/// Wraps an azimuth in degrees onto the circle, into (-180, 180].
///
/// OAR's OLR does not normalize out-of-range azimuths: its rear
/// front-back folding covers [-180, 180] only, and its closest-speaker
/// fallback compares angles linearly, so an unwrapped value (e.g.
/// az 180 + spread/2 = 270) collapses onto one speaker instead of
/// landing at the equivalent in-range direction (-90). See ES-436.
///
/// The boundary maps to +180 (not -180) to match OAR's conventions:
/// OBR normalizes to (-180, 180], and OLR's layout table defines the
/// back-center speaker at exactly +180 (M+180) with no -180 twin — the
/// linear closest-speaker compare would score -180 as 360 degrees away
/// from it.
double _wrapAzimuthDeg(double az) => 180.0 - ((180.0 - az) % 360.0);

/// Polar position payload for an Object element, shared by the live
/// engine push and the offline loudness/measure path so both render the
/// object identically. A dual object becomes two positions spread
/// symmetrically around the azimuth (az ± spread/2), each wrapped onto
/// (-180, 180], matching how the spread parameter is presented in the
/// object controls. Azimuth passes through in the IAMF polar convention
/// (positive = left of front-center). Elevation is clamped to [-90, 90]
/// and distance to [0, 1] (not wrapped — out-of-range values can only
/// come from hand-edited session JSON; sliders are bounded). The second
/// triplet is meaningful only when count == 2.
({
  int count,
  double az,
  double el,
  double dist,
  double az2,
  double el2,
  double dist2,
})
elementObjectPolarPositions(AudioElement el) {
  final elevation = el.elevation.clamp(-90.0, 90.0);
  final distance = el.distance.clamp(0.0, 1.0);
  if (el.isDual) {
    final half = el.spread / 2;
    return (
      count: 2,
      az: _wrapAzimuthDeg(el.azimuth + half),
      el: elevation,
      dist: distance,
      az2: _wrapAzimuthDeg(el.azimuth - half),
      el2: elevation,
      dist2: distance,
    );
  }
  return (
    count: 1,
    az: _wrapAzimuthDeg(el.azimuth),
    el: elevation,
    dist: distance,
    az2: 0,
    el2: 0,
    dist2: 1,
  );
}

/// Push an Object element's polar position(s) to the engine. No-op for
/// channel/scene elements. REQUIRED for object audibility on loudspeaker
/// monitoring layouts: OAR's object-to-loudspeaker renderer only starts
/// rendering an object once position metadata arrives, so every path
/// that registers or repositions an Object element must call this
/// (element sync, session load, position slider changes).
void pushElementObjectPosition(EclipsaStudioEngine engine, AudioElement el) {
  if (el.type != 'Object') return;
  final pos = elementObjectPolarPositions(el);
  engine.setElementObjectPosition(
    el.id,
    count: pos.count,
    azimuth: pos.az,
    elevation: pos.el,
    distance: pos.dist,
    azimuth2: pos.az2,
    elevation2: pos.el2,
    distance2: pos.dist2,
  );
}

/// Maps layout string to (oar_layout_t, channel_count).
/// Values must match oar_layout_t enum in oar.h.
(int, int) _layoutToOar(String layout) {
  if (layout.contains('9.1.6')) return (10, 16);
  if (layout.contains('7.1.5.4') || layout.contains('7154')) return (12, 16);
  if (layout.contains('7.1.4')) return (8, 12);
  if (layout.contains('7.1.2')) return (7, 10);
  if (layout.contains('7.1')) return (6, 8);
  if (layout.contains('5.1.4')) return (5, 10);
  if (layout.contains('5.1.2')) return (4, 8);
  if (layout.contains('5.1')) return (3, 6);
  if (layout.contains('3.1.2')) return (9, 6);
  if (layout.contains('stereo')) return (2, 2);
  if (layout.contains('mono')) return (1, 1);
  return (2, 2); // fallback to stereo
}

int _ambisonicsChannels(int order) {
  return (order + 1) * (order + 1); // (N+1)^2
}

