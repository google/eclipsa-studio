  /// selector never lands on an option it doesn't show. A value written by a
  /// newer build (or one unsupported on this OS, or a retired backend's name
  /// such as `mediaKit`/`fvp`) falls back to the default `auto` — and the
  /// backend itself still falls back via `resolveBackendKind`.
  void restore(String name) {
