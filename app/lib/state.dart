/// What the follow-system-default device poll should do: the device
/// to be on, and whether getting there needs a stream reopen.
typedef FollowSystemDefaultAction = ({int index, bool reopen});

/// Poll decision for follow-system-default mode (ES-467): what the
/// device poll should do after a refresh, given the freshly enumerated
/// [devices], the name of the device the output was on before the
/// refresh ([openDeviceName], null when nothing was resolved), and the
/// pre-refresh selection index. Returns null when no action is needed;
/// otherwise `index` is the device to be on and `reopen` says whether
/// the stream must be reopened (the OS default moved to a different
/// device) or the open device merely shifted enumeration index (re-pin
/// the selection, leave the stream untouched).
///
/// Pure so the decision rule is unit-testable without audio hardware —
/// same pattern as the engine's `DeviceManager::ResolveSelectedIndex`.
FollowSystemDefaultAction? followSystemDefaultAction(
  List<AudioDeviceInfo> devices,
  String? openDeviceName,
  int selectedIndex,
) {
  var defaultIdx = -1;
  for (var i = 0; i < devices.length; i++) {
    if (devices[i].isDefault) {
      defaultIdx = i;
      break;
    }
  }
  if (defaultIdx < 0) return null;
  if (devices[defaultIdx].name == openDeviceName) {
    if (defaultIdx == selectedIndex) return null;
    return (index: defaultIdx, reopen: false);
  }
  return (index: defaultIdx, reopen: true);
}

/// Channel count of the currently-selected output device (2 if none).
/// Single source of truth for the routing matrix and the target switcher.
final outputDeviceChannelsProvider = Provider<int>((ref) {
  final devices = ref.watch(audioDevicesProvider);
  if (devices.isEmpty) return 2;
  final settings = ref.watch(audioSettingsProvider);
  final idx = settings.deviceIndex.clamp(0, devices.length - 1);
  return devices[idx].maxChannels;
});

