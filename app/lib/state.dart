// --- Per-element settings within a sub-mix ---

class MixElementSettings {
  final int elementId;
  final bool included;
  final double mixGain; // dB, element mix gain (separate from element gain)
  final HeadphonesRenderingMode headphonesMode;

  /// IAMF `element_rendering_config.binaural_filter_profile` — HRIR family
  /// used when this element is binauralized. No effect when
  /// [headphonesMode] is [HeadphonesRenderingMode.stereo] (the element is
  /// downmixed to stereo instead of being spatialized).
  final BinauralProfile binauralProfile;

  const MixElementSettings({
    required this.elementId,
    this.included = true,
    this.mixGain = 0,
    // Mode 1 / world-locked is unambiguous across all IAMF element types
    // (channel/scene/object). Mode 0 is a trap: for channel-based elements
    // it means "downmix to stereo", for scene/object it means
    // "binaural world-locked" — same as mode 1. Defaulting to mode 1
    // avoids that asymmetry and matches the user-visible "Binaural
    // World-locked" label regardless of element type.
    this.headphonesMode = HeadphonesRenderingMode.binauralWorldLocked,
    this.binauralProfile = BinauralProfile.ambient,
  });

  MixElementSettings copyWith({
    bool? included,
    double? mixGain,
    HeadphonesRenderingMode? headphonesMode,
    BinauralProfile? binauralProfile,
  }) {
    return MixElementSettings(
      elementId: elementId,
      included: included ?? this.included,
      mixGain: mixGain ?? this.mixGain,
      headphonesMode: headphonesMode ?? this.headphonesMode,
      binauralProfile: binauralProfile ?? this.binauralProfile,
    );
  }

  /// Returns the headphones-rendering mode that should be pushed to OAR
  /// for [el], coercing to [HeadphonesRenderingMode.stereo] (IAMF mode
  /// 0) when [el] is channel-based with a Binaural layout. Mode 0 is
  /// the canonical "pre-rendered binaural content" signal and the only
  /// value that is unambiguously correct for every IAMF decoder.
  /// OBR's reference implementation handles all modes as a direct L/R
  /// passthrough for these elements anyway, so the coercion does not
  /// change what the user hears — it exists to keep the bitstream value
  /// honest. The stored [headphonesMode] is left untouched so that
  /// toggling an element's type back and forth preserves user intent.
  HeadphonesRenderingMode effectiveHeadphonesMode(AudioElement el) {
    if (el.isChannelBasedBinaural) return HeadphonesRenderingMode.stereo;
    return headphonesMode;
  }
}

// --- Sub-mix (IAMF: 1 or 2 per mix presentation) ---

class SubMix {
  final String label; // e.g. "Main", "Commentary"
  final double outputMixGain; // dB, master fader for this sub-mix
  final List<MixElementSettings> elementSettings;
  final List<MixLayout> layouts;

  const SubMix({
    this.label = 'Main',
    this.outputMixGain = 0,
    this.elementSettings = const [],
    this.layouts = const [MixLayout(soundSystem: SoundSystem.stereo)],
  });

  SubMix copyWith({
    String? label,
    double? outputMixGain,
    List<MixElementSettings>? elementSettings,
    List<MixLayout>? layouts,
  }) {
    return SubMix(
      label: label ?? this.label,
      outputMixGain: outputMixGain ?? this.outputMixGain,
      elementSettings: elementSettings ?? this.elementSettings,
      layouts: layouts ?? this.layouts,
    );
  }

  /// Get settings for a specific element, or defaults if not set.
  MixElementSettings settingsFor(int elementId) {
    return elementSettings.firstWhere(
      (s) => s.elementId == elementId,
      orElse: () => MixElementSettings(elementId: elementId),
    );
  }
}

// --- Mix Presentation ---

class Mix {
  final int id;
  final String name;
  final String language;

  /// IAMF sub-mixes (1 or 2). Each has its own elements, gain, and layouts.
  final List<SubMix> subMixes;

  const Mix({
    required this.id,
    required this.name,
    this.language = 'en',
    this.subMixes = const [SubMix()],
  });

  Mix copyWith({String? name, String? language, List<SubMix>? subMixes}) {
    return Mix(
      id: id,
      name: name ?? this.name,
      language: language ?? this.language,
      subMixes: subMixes ?? this.subMixes,
    );
  }

  // ── Convenience accessors for the active (first) sub-mix ──

  /// Output mix gain of the first sub-mix.
  double get outputMixGain =>
      subMixes.isNotEmpty ? subMixes[0].outputMixGain : 0;

  /// Element settings of the first sub-mix.
  List<MixElementSettings> get elementSettings =>
      subMixes.isNotEmpty ? subMixes[0].elementSettings : const [];

  /// Layouts of the first sub-mix.
  List<MixLayout> get layouts =>
      subMixes.isNotEmpty ? subMixes[0].layouts : const [];

  /// Get settings for a specific element in the first sub-mix.
  MixElementSettings settingsFor(int elementId) {
    return subMixes.isNotEmpty
        ? subMixes[0].settingsFor(elementId)
        : MixElementSettings(elementId: elementId);
  }

  /// Update a specific sub-mix by index.
  Mix updateSubMix(int index, SubMix Function(SubMix) updater) {
    final list = List<SubMix>.from(subMixes);
    if (index >= 0 && index < list.length) {
      list[index] = updater(list[index]);
    }
    return copyWith(subMixes: list);
  }
}

// --- Transport state ---

class TransportState {
  final int samplePosition;
  final int sampleRate;
  final int durationSamples;

  /// Where return-on-stop puts the playhead: set when playback starts
  /// and moved by mid-playback user relocations (ES-277). A selected
  /// loop region overrides it — see [TransportNotifier.returnToPlayStart].
  final int? playStartPosition;

  const TransportState({
    this.samplePosition = 0,
    this.sampleRate = 48000,
    this.durationSamples = 48000 * 312, // default 312s
    this.playStartPosition,
  });

  double get seconds => samplePosition / sampleRate;
  double get durationSeconds => durationSamples / sampleRate;
  double get fraction =>
      durationSamples > 0 ? samplePosition / durationSamples : 0;

  TransportState copyWith({
    int? samplePosition,
    int? sampleRate,
    int? durationSamples,
    int? playStartPosition,
    bool clearPlayStart = false,
  }) {
    return TransportState(
      samplePosition: samplePosition ?? this.samplePosition,
      sampleRate: sampleRate ?? this.sampleRate,
      durationSamples: durationSamples ?? this.durationSamples,
      playStartPosition: clearPlayStart
          ? null
          : (playStartPosition ?? this.playStartPosition),
    );
  }
}

class TransportNotifier extends Notifier<TransportState> {
  /// True when a non-advance position change occurred since the last
  /// [consumeSeek]. The tick loop checks this to sync the C++ engine.
  bool _seeked = false;

  /// Wall-clock microsecond stamp of the last clamp warning; used to
  /// rate-limit the log in [setSamplePosition] (called at 60 Hz).
  int _lastClampWarnMicros = 0;

  /// Returns true (once) if a seek happened since the last call.
  bool consumeSeek() {
    final v = _seeked;
    _seeked = false;
    return v;
  }

  /// True while a seek is armed but not yet consumed. Lets the tick
  /// loop's scrub coalescing (ES-473) hold a pending seek across ticks
  /// without the engine-position read-back stomping the dragged
  /// playhead in the meantime.
  bool get seekPending => _seeked;

  @override
  TransportState build() => const TransportState();

  void advance(double dt) {
    final s = state;
    final delta = (dt * s.sampleRate).round();
    final newPos = (s.samplePosition + delta).clamp(0, s.durationSamples);
    state = s.copyWith(samplePosition: newPos);
  }

  /// Update [TransportState.samplePosition] without arming the seek
  /// flag. Use this for position updates that originate from the
  /// engine (e.g., the audio-thread frame counter), so the tick loop
  /// does not bounce the value back via `transportSeek()`.
  ///
  /// If [frames] is outside `[0, durationSamples]` it is clamped and
  /// a debounced warning is logged — an out-of-range read usually
  /// indicates a sample-rate or duration desync between Dart and the
  /// engine.
  void setSamplePosition(int frames) {
    final clamped = frames.clamp(0, state.durationSamples);
    if (clamped != frames) {
      final now = DateTime.now().microsecondsSinceEpoch;
      // Rate-limit to at most one warning per second.
      if (now - _lastClampWarnMicros > 1000000) {
        _lastClampWarnMicros = now;
        Log.w(
          LogCat.transport,
          'Audio-thread position $frames out of range '
          '[0, ${state.durationSamples}] — clamped. Likely '
          'sample-rate or duration desync.',
        );
      }
    }
    state = state.copyWith(samplePosition: clamped);
  }

  /// User-facing playhead relocation (timeline click/drag, scrub bar).
  ///
  /// While the transport is rolling the relocation also becomes the
  /// new play-start, so return-on-stop comes back to where the user
  /// last placed the playhead instead of where playback originally
  /// began (ES-277) — DAW convention. Internal seeks (loop wrap, session
  /// restore, go-to-end) use [seekSample]/[resetPosition] and must not
  /// move the play-start.
  void seek(double fraction) {
    final pos = (fraction.clamp(0.0, 1.0) * state.durationSamples).round();
    state = state.copyWith(
      samplePosition: pos,
      // null → copyWith keeps the existing mark when stopped.
      playStartPosition: ref.read(playingProvider) ? pos : null,
    );
    _seeked = true;
  }

  void seekSample(int sample) {
    state = state.copyWith(
      samplePosition: sample.clamp(0, state.durationSamples),
    );
    _seeked = true;
  }

  void seekSeconds(double seconds) {
    final pos = (seconds * state.sampleRate).round().clamp(
      0,
      state.durationSamples,
    );
    state = state.copyWith(samplePosition: pos);
    _seeked = true;
  }

  void updateDuration(int samples, int sampleRate) {
    state = state.copyWith(durationSamples: samples, sampleRate: sampleRate);
  }

  /// Re-base sampleRate (and proportionally rescale durationSamples,
  /// samplePosition, playStartPosition) so the timeline length in
  /// seconds is preserved while the underlying clock changes. Called
  /// when the audio engine reconfigures to a new device sample rate
  /// mid-session — the engine starts producing position_frames at the
  /// new rate, so Dart needs to follow or seek round-trips drift the
  /// playhead by the rate ratio. No seek is armed.
  void rebaseSampleRate(int newSampleRate) {
    final s = state;
    if (newSampleRate <= 0 || newSampleRate == s.sampleRate) return;
    final ratio = newSampleRate / s.sampleRate;
    state = TransportState(
      sampleRate: newSampleRate,
      durationSamples: (s.durationSamples * ratio).round(),
      samplePosition: (s.samplePosition * ratio).round().clamp(0, 1 << 62),
      playStartPosition: s.playStartPosition == null
          ? null
          : (s.playStartPosition! * ratio).round(),
    );
  }

  void resetPosition() {
    state = state.copyWith(samplePosition: 0, clearPlayStart: true);
    _seeked = true;
  }

  /// Mark the current position as the play-start point.
  void markPlayStart() {
    state = state.copyWith(playStartPosition: state.samplePosition);
  }

  /// Return to the position where playback started (or 0).
  ///
  /// A selected loop region takes precedence: stop always returns to
  /// the region's start (ES-277), whether or not the playhead was
  /// relocated mid-playback.
  void returnToPlayStart() {
    final region = ref.read(loopRegionProvider);
    final pos = region != null
        ? region.startSample.clamp(0, state.durationSamples)
        : (state.playStartPosition ?? 0);
    state = state.copyWith(samplePosition: pos, clearPlayStart: true);
    _seeked = true;
  }
}

