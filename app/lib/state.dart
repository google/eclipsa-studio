/// Remembers a (device, hardware-rate) pair whose follow attempt
/// failed, so the rate-follow poll doesn't repeat a doomed device
/// close/reopen every poll cycle (ES-33's retry storm). The latch holds
/// until the hardware rate or the device changes — the only events
/// that can change the outcome — or until the rates agree again.
class RateFollowLatch {
  int? _deviceIndex;
  int? _hwRate;

  bool get isSet => _hwRate != null;

  /// True when [deviceIndex]/[hwRate] are the exact pair that already
  /// failed — the caller should skip the follow attempt.
  bool matches(int deviceIndex, int hwRate) =>
      _deviceIndex == deviceIndex && _hwRate == hwRate;

  void set(int deviceIndex, int hwRate) {
    _deviceIndex = deviceIndex;
    _hwRate = hwRate;
  }

  void clear() {
    _deviceIndex = null;
    _hwRate = null;
  }
}

/// All enumerated output devices. Empty list if the engine is unavailable.
///
/// The list is refreshed at runtime by the device poll in app_shell
/// (hot-plug, OS default-device changes) via [AudioDevicesNotifier.refresh]
/// — watchers like the settings picker and the "(default)" badge follow.
class AudioDevicesNotifier extends Notifier<List<AudioDeviceInfo>> {
  @override
  List<AudioDeviceInfo> build() {
    final engine = ref.watch(eclipsaStudioEngineProvider);
    if (engine == null) return const [];
    return engine.getAudioDevices();
  }

  /// Re-enumerate and publish the device list if anything changed.
  /// Returns true when an update was published.
  bool refresh() {
    final engine = ref.read(eclipsaStudioEngineProvider);
    if (engine == null) return false;
    engine.refreshDevices();
    final next = engine.getAudioDevices();
    if (_sameDevices(state, next)) return false;
    state = next;
    return true;
  }

  static bool _sameDevices(List<AudioDeviceInfo> a, List<AudioDeviceInfo> b) {
    if (a.length != b.length) return false;
    for (var i = 0; i < a.length; i++) {
      if (a[i].name != b[i].name ||
          a[i].isDefault != b[i].isDefault ||
          a[i].maxChannels != b[i].maxChannels) {
        return false;
      }
    }
    return true;
  }
}

