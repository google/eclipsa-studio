/// OAR target layout options (matching oar_layout_t values).
/// Values must match oar_layout_t in oar.h:
/// none=0, mono=1, stereo=2, 5.1=3, 5.1.2=4, 5.1.4=5,
/// 7.1=6, 7.1.2=7, 7.1.4=8, 3.1.2=9, 9.1.6=10, binaural=0xFF
enum OarLayout {
  stereo(2, 'Stereo', 2),
  layout51(3, '5.1', 6),
  layout512(4, '5.1.2', 8),
  layout514(5, '5.1.4', 10),
  layout71(6, '7.1', 8),
  layout712(7, '7.1.2', 10),
  layout714(8, '7.1.4', 12),
  layout916(10, '9.1.6', 16),
  binaural(0xFF, 'Binaural', 2);

  const OarLayout(this.oarValue, this.label, this.channels);
  final int oarValue;
  final String label;
  final int channels;
}

/// Memoized [OarLayoutSpeakers.speakerLabels] — the getter sits in
/// 60 Hz meter build paths, and a stable list identity lets
/// `MultichannelMeterPainter.shouldRepaint` short-circuit via
/// `identical()` inside `listEquals`.
final Map<OarLayout, List<String>> _speakerLabelsCache = {};

extension OarLayoutSpeakers on OarLayout {
  /// Per-channel speaker labels in the engine's output channel order
  /// (OAR / IAMF / ITU-R BS.2051), via the authoritative label source
  /// in `widgets/routing_labels.dart`. A hand-kept table here had
  /// 9.1.6 in the wrong order (ES-552: OAR renders L60/R60 first and
  /// the rears at index 4–5, not wides-then-sides). Length always
  /// equals [channels].
  ///
  /// The order, and [oarValue], are pinned against
  /// `engine/renderer/oar_output_channels.txt` in
  /// `test/renderer/oar_output_channels_test.dart` — which
  /// `engine/test/oar_output_channels_test.cc` pins against what OAR
  /// actually renders, so an OAR pin bump that reorders a layout fails
  /// instead of relabelling these silently (ES-592).
  List<String> get speakerLabels => _speakerLabelsCache.putIfAbsent(this, () {
    // The disambiguation hint for count-ambiguous layouts (8ch is
    // 5.1.2 or 7.1, 10ch is 5.1.4 or 7.1.2) is keyed on the enum, not
    // on [label]: display text must be freely renamable without
    // silently flipping which channel order a layout's labels follow.
    final hint = switch (this) {
      OarLayout.layout512 => '5.1.2',
      OarLayout.layout712 => '7.1.2',
      _ => null,
    };
    return List.unmodifiable(
      iamfChannelLabels(channelCount: channels, layoutHint: hint),
    );
  });
}

/// Device-channel ceiling for routing bitmasks. Matches the engine's
/// kMaxRoutingChannels — one Dart int (64-bit) spans the whole range.
const int kMaxRoutingChannels = 64;

/// One switchable output target: an OAR layout plus its routing into the
/// physical device channels. Generalizes the old single-layout config.
class OutputTarget {
  final OarLayout layout;

  /// Per-OAR-channel device-channel routing. `routing[oarCh]` is a
  /// bitmask: bit `d` set = OAR channel `oarCh` feeds device channel `d`;
  /// `0` = muted. One `int` (Dart ints are 64-bit) spans the full
  /// 64-channel device range. This is the exact shape the Phase 2 engine
  /// FFI consumes. Length always equals `layout.channels`.
  final List<int> routing;

  const OutputTarget({required this.layout, required this.routing});

  /// Identity patch: OAR channel `i` feeds device channel `i`.
  factory OutputTarget.identity(OarLayout layout) => OutputTarget(
    layout: layout,
    routing: List<int>.generate(layout.channels, (i) => 1 << i),
  );

  OutputTarget copyWith({List<int>? routing}) =>
      OutputTarget(layout: layout, routing: routing ?? this.routing);

  Map<String, dynamic> toJson() => {'layout': layout.name, 'routing': routing};

  /// Decode one target. Defensive: returns null for an unknown layout, and
  /// reconciles the routing length to `layout.channels` (pads missing
  /// channels with identity, truncates extras). Never throws.
  static OutputTarget? fromJson(Map<String, dynamic> j) {
    final layout = OarLayout.values
        .where((l) => l.name == j['layout'])
        .firstOrNull;
    if (layout == null) return null;
    final rawList = j['routing'];
    final raw = rawList is List
        ? rawList.whereType<int>().toList()
        : const <int>[];
    final routing = List<int>.generate(
      layout.channels,
      (i) => i < raw.length ? raw[i] : (1 << i),
    );
    return OutputTarget(layout: layout, routing: routing);
  }
}

/// Ceiling on the exposed monitoring target set (ES-591). Each [OarLayout]
/// can appear at most once, so today's nine layouts cannot actually reach
/// it — the cap records the decision and guards [MonitoringConfig.fromJson]
/// and [MonitoringConfigNotifier.addTarget] against a future where the
/// layout enum outgrows what the switcher column can hold.
const int kMaxExposedMonitoringTargets = 10;

/// Monitoring output configuration: an ordered, curated set of switchable
/// output targets plus the active one. Exactly one target is live at a
/// time (single-renderer); switching restores that target's saved patch.
///
/// Invariants: at least one target; each [OarLayout] appears at most once
/// (layout is both the active key and the per-target identity); at most
/// [kMaxExposedMonitoringTargets] targets.
class MonitoringConfig {
  /// Exposed set, ordered left-to-right (matrix column groups + switcher).
  final List<OutputTarget> targets;

  /// The live target's layout. Keyed by layout, not list index, so it
  /// survives reorder/remove.
  final OarLayout activeLayout;

  /// Pink-noise calibration reference (dBFS RMS). Cosmetic until the
  /// Phase 2 noise engine.
  final double noiseDbfs;

  static const double kDefaultNoiseDbfs = -40.0;

  const MonitoringConfig({
    required this.targets,
    required this.activeLayout,
    this.noiseDbfs = kDefaultNoiseDbfs,
  });

  /// First-run / unknown-device default: Stereo + Binaural, Stereo live.
  factory MonitoringConfig.initial() => MonitoringConfig(
    targets: [
      OutputTarget.identity(OarLayout.stereo),
      OutputTarget.identity(OarLayout.binaural),
    ],
    activeLayout: OarLayout.stereo,
  );

  /// The live target. Falls back to the first target if [activeLayout]
  /// isn't present, keeping callers null-safe.
  OutputTarget get active => targets.firstWhere(
    (t) => t.layout == activeLayout,
    orElse: () => targets.first,
  );

  bool isExposed(OarLayout l) => targets.any((t) => t.layout == l);

  // Back-compat accessors: existing readers (renderer view, meters, status
  // bar, engine push) see the active target's layout/routing unchanged.
  OarLayout get layout => active.layout;
  List<int> get routing => active.routing;
  bool get isBinaural => layout == OarLayout.binaural;

  MonitoringConfig copyWith({
    List<OutputTarget>? targets,
    OarLayout? activeLayout,
    double? noiseDbfs,
  }) {
    return MonitoringConfig(
      targets: targets ?? this.targets,
      activeLayout: activeLayout ?? this.activeLayout,
      noiseDbfs: noiseDbfs ?? this.noiseDbfs,
    );
  }

  /// A copy with every target's routing clamped to a device with
  /// [maxChannels] channels (bits feeding device channel >= [maxChannels]
  /// cleared).
  ///
  /// This is a VIEW for the engine-push boundary only — never store or
  /// persist the result. State and disk always hold the full routing so
  /// it survives device switches and channel-count changes (ES-24, ES-63).
  MonitoringConfig clampedToDeviceChannels(int maxChannels) {
    // Every device channel index already fits in 64 bits — no bits to clear.
    if (maxChannels >= kMaxRoutingChannels) return this;
    final mask = (1 << maxChannels) - 1;
    return copyWith(
      targets: [
        for (final t in targets)
          t.copyWith(routing: [for (final r in t.routing) r & mask]),
      ],
    );
  }

  /// Per-device serialized slice. Labels live in a separate provider and
  /// are merged by the monitoring store layer.
  Map<String, dynamic> toJson() => {
    'v': 1,
    'active': activeLayout.name,
    'targets': [for (final t in targets) t.toJson()],
    'noiseDbfs': noiseDbfs,
  };

  /// Decode a per-device slice. Total (never throws): unknown layouts are
  /// dropped, a duplicated layout keeps its first entry (the invariant is
  /// enforced on untrusted input, not assumed), the set is trimmed to
  /// [kMaxExposedMonitoringTargets] (ES-591), an empty/garbage set falls
  /// back to [MonitoringConfig.initial], missing fields default.
  static MonitoringConfig fromJson(Map<String, dynamic> j) {
    final rawTargets = j['targets'];
    final seen = <OarLayout>{};
    final targets =
        [
              for (final t in (rawTargets is List ? rawTargets : const []))
                if (t is Map) OutputTarget.fromJson(t.cast<String, dynamic>()),
            ]
            .whereType<OutputTarget>()
            .where((t) => seen.add(t.layout))
            .take(kMaxExposedMonitoringTargets)
            .toList();
    final base = targets.isEmpty ? MonitoringConfig.initial().targets : targets;
    final active =
        OarLayout.values.where((l) => l.name == j['active']).firstOrNull ??
        base.first.layout;
    final noise = j['noiseDbfs'];
    return MonitoringConfig(
      targets: base,
      activeLayout: base.any((t) => t.layout == active)
          ? active
          : base.first.layout,
      noiseDbfs: noise is num ? noise.toDouble() : kDefaultNoiseDbfs,
    );
  }
}

class MonitoringConfigNotifier extends Notifier<MonitoringConfig> {
  @override
  MonitoringConfig build() => MonitoringConfig.initial();

  void set(MonitoringConfig v) => state = v;

  /// Make [layout] the live target. No-op if it isn't exposed.
  void setActive(OarLayout layout) {
    if (layout == state.activeLayout || !state.isExposed(layout)) return;
    state = state.copyWith(activeLayout: layout);
    // Noise toggles are per-layout calibration indexed by channel; clear them
    // so they don't carry across a target switch.
    ref.read(noiseInjectionProvider.notifier).killAll();
  }

  /// Append [layout] with an identity patch, if not already exposed and
  /// the exposed set is under [kMaxExposedMonitoringTargets] (ES-591).
  /// Does not change which target is live.
  void addTarget(OarLayout layout) {
    if (state.isExposed(layout) ||
        state.targets.length >= kMaxExposedMonitoringTargets) {
      return;
    }
    state = state.copyWith(
      targets: [...state.targets, OutputTarget.identity(layout)],
    );
  }

  /// Remove [layout]. Always keeps >=1 target; if the removed target was
  /// live, the first remaining target becomes live.
  void removeTarget(OarLayout layout) {
    if (state.targets.length <= 1 || !state.isExposed(layout)) return;
    final next = state.targets.where((t) => t.layout != layout).toList();
    final active = layout == state.activeLayout
        ? next.first.layout
        : state.activeLayout;
    state = state.copyWith(targets: next, activeLayout: active);
  }

  /// Reorder the exposed set (matrix column groups + switcher order),
  /// following the [ReorderableListView.onReorderItem] index
  /// convention: [newIndex] is the insertion position after the item
  /// is removed (pre-adjusted for downward drags by the framework).
  void reorderTarget(int oldIndex, int newIndex) {
    if (oldIndex < 0 || oldIndex >= state.targets.length) return;
    final list = [...state.targets];
    final insert = newIndex.clamp(0, list.length - 1);
    list.insert(insert, list.removeAt(oldIndex));
    state = state.copyWith(targets: list);
  }

  /// Replace the active target's routing map.
  void setActiveRouting(List<int> routing) {
    state = state.copyWith(
      targets: [
        for (final t in state.targets)
          t.layout == state.activeLayout ? t.copyWith(routing: routing) : t,
      ],
    );
  }

  /// Toggle one cross-point cell on [layout]'s patch: OAR channel [oarCh]
  /// to device channel [devCh]. Independent toggle — does not clear other
  /// cells, so splits (one OAR ch → many device ch) and sums (many → one)
  /// are both expressible.
  void toggleCell(OarLayout layout, int oarCh, int devCh) {
    if (devCh < 0 || devCh >= kMaxRoutingChannels) return;
    state = state.copyWith(
      targets: [
        for (final t in state.targets)
          if (t.layout == layout)
            t.copyWith(routing: _toggled(t.routing, oarCh, devCh))
          else
            t,
      ],
    );
  }

  static List<int> _toggled(List<int> routing, int oarCh, int devCh) {
    if (oarCh < 0 || oarCh >= routing.length) return routing;
    final next = [...routing];
    next[oarCh] ^= 1 << devCh;
    return next;
  }

  void setNoiseDbfs(double dbfs) => state = state.copyWith(noiseDbfs: dbfs);

  // NOTE: there is intentionally no destructive clamp here. Out-of-range
  // routing (device has fewer channels than the patch uses) is masked at
  // the engine-push boundary via [MonitoringConfig.clampedToDeviceChannels]
  // and simply not displayed by the matrix; the full patch stays in state
  // and on disk so it restores when the channels come back (ES-24, ES-63).
}

final monitoringConfigProvider =
    NotifierProvider<MonitoringConfigNotifier, MonitoringConfig>(
      MonitoringConfigNotifier.new,
    );

/// Which axis the single lit noise cell sits on, or [none] when off.
enum NoiseCell { none, row, col }

/// Pink-noise calibration overlay on the routing matrix. A single generator
/// drives one cell at a time — no summing. The lit cell is either a row
/// (pre-routing, indexed by active-target OAR channel — signal-path test) or
/// a column (post-routing, indexed by device channel — wiring test);
/// selecting another cell moves the generator. Cosmetic in Phase 1 — the
/// engine generator arrives in Phase 2.
class NoiseInjection {
  final NoiseCell cell;

  /// Channel index of the lit cell: OAR channel for a row, device channel
  /// for a column. Meaningless when [cell] is [NoiseCell.none].
  final int channel;

  const NoiseInjection({this.cell = NoiseCell.none, this.channel = 0});

  bool get anyOn => cell != NoiseCell.none;
  bool rowOn(int ch) => cell == NoiseCell.row && channel == ch;
  bool colOn(int ch) => cell == NoiseCell.col && channel == ch;
}

class NoiseInjectionNotifier extends Notifier<NoiseInjection> {
  @override
  NoiseInjection build() => const NoiseInjection();

  /// Light the row cell for OAR channel [ch], moving the single generator
  /// there; clears it if that cell was already lit.
  void toggleRow(int ch) => state = state.rowOn(ch)
      ? const NoiseInjection()
      : NoiseInjection(cell: NoiseCell.row, channel: ch);

  /// Light the column cell for device channel [ch], moving the single
  /// generator there; clears it if that cell was already lit.
  void toggleCol(int ch) => state = state.colOn(ch)
      ? const NoiseInjection()
      : NoiseInjection(cell: NoiseCell.col, channel: ch);

  /// The matrix kill-all corner: clears the lit noise cell.
  void killAll() => state = const NoiseInjection();
}

final noiseInjectionProvider =
    NotifierProvider<NoiseInjectionNotifier, NoiseInjection>(
      NoiseInjectionNotifier.new,
    );

