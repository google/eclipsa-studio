/// ES-535: the loop-end wrap is edge-triggered — it fires only when
/// playback crossed [effectiveEnd] this tick ([prevPos] before it,
/// [pos] at or past it) without a user seek armed. A deliberate
/// placement past the region must stick (the loop stays armed).
bool shouldLoopWrap({
  required int prevPos,
  required int pos,
  required int effectiveEnd,
  required bool userSeekArmed,
}) =>
    effectiveEnd > 0 &&
    !userSeekArmed &&
    prevPos < effectiveEnd &&
    pos >= effectiveEnd;

/// Companion to [shouldLoopWrap] (ES-535): whether the playhead has run
/// into the timeline end. Level-triggered on purpose — there is
/// nothing past the timeline end to respect a placement at.
///
/// [durationSamples] == 0 means the duration is not known yet (IAMF
/// lazy scan still running) — without the guard, position 0 already
/// counts as "past the end" and the first tick after Play pauses the
/// transport, so a freshly opened IAMF appears silent until the scan
/// completes.
bool shouldWrapAtTimelineEnd({
  required int pos,
  required int durationSamples,
}) => durationSamples > 0 && pos >= durationSamples;

/// Longest audio-element duration in seconds — the audio contribution
/// to the timeline extent. Elements without a loaded WAV contribute
/// nothing; returns 0 when none qualify.
///
/// Durations must be compared in *seconds*, never by frame count: a
/// higher-rate file packs more frames into fewer seconds, so ordering
/// by `totalSamples` can crown a shorter file, truncating the timeline
/// mid-clip in mixed-sample-rate sessions.
double longestAudioSeconds(Iterable<AudioElement> elements) {
  var seconds = 0.0;
  for (final e in elements) {
    final info = e.wavInfo;
    if (info != null && info.durationSeconds > seconds) {
      seconds = info.durationSeconds;
    }
  }
  return seconds;
}

/// Loop region in sample positions, or null if no selection.
class LoopRegion {
  final int startSample;
  final int endSample;

  const LoopRegion({required this.startSample, required this.endSample})
    : assert(startSample >= 0),
      assert(endSample > startSample);

  double startSeconds(int sampleRate) => startSample / sampleRate;
  double endSeconds(int sampleRate) => endSample / sampleRate;
  double startFraction(int durationSamples) =>
      durationSamples > 0 ? startSample / durationSamples : 0;
  double endFraction(int durationSamples) =>
      durationSamples > 0 ? endSample / durationSamples : 0;
}

class LoopRegionNotifier extends Notifier<LoopRegion?> {
  @override
  LoopRegion? build() => null;

  /// Resetting an existing region (Escape, timeline double-click,
  /// degenerate drag) also disarms the loop toggle — the loop the user
  /// was playing with is gone, and keeping the toggle armed would
  /// silently re-loop the whole timeline on the next play (ES-277).
  /// A toggle armed *without* a region is the deliberate
  /// whole-timeline loop mode and is only ever switched off by the
  /// user, so a no-op clear must not touch it.
  void set(LoopRegion? v) {
    final hadRegion = state != null;
    state = v;
    if (v == null && hadRegion) {
      ref.read(loopingProvider.notifier).set(false);
    }
  }

  void clear() => set(null);

  /// Set from fractional positions (0–1).
  void setFromFractions(double startFrac, double endFrac) {
    final transport = ref.read(transportProvider);
    final duration = transport.durationSamples;
    final s = (startFrac.clamp(0, 1) * duration).round();
    final e = (endFrac.clamp(0, 1) * duration).round();
    if (s == e) {
      set(null);
    } else {
      state = LoopRegion(startSample: s < e ? s : e, endSample: s < e ? e : s);
    }
  }
}

