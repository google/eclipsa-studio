  const IamfProfile({
    required this.label,
    required this.profileIndex,
    required this.specVersion,
    required this.maxAudioElements,
    required this.maxChannels,
    required this.maxSubMixesPerMix,
    required this.maxCodecConfigs,
    required this.allowObjectBased,
    required this.allowMixedTypes,
  });

  final String label;

  /// IAMF `primary_profile` field value.
  final int profileIndex;

  /// IAMF spec version this profile complies with. Gates version-specific
  /// features (expanded layouts, head-locked binaural, binaural filter
  /// profile) — see iamf_profile_rules.dart.
  final IamfSpecVersion specVersion;
  final int maxAudioElements;
  final int maxChannels;

  /// Max sub-mixes per mix presentation (1 for stable profiles, 2 for the
  /// v2.0.0 draft profiles). Mirrors iamf-tools profile_filter.cc.
  final int maxSubMixesPerMix;

  /// Max unique Codec Config OBUs (1 stable / 2 draft). Provisional for the
  /// draft profiles.
  final int maxCodecConfigs;
  final bool allowObjectBased;

  /// Whether object-based elements can coexist with channel/scene in
  /// the same mix presentation. Base-Advanced allows objects but
  /// restricts the first mix presentation (objects-only if any objects
  /// are present) — that constraint is checked at export/validation
  /// time, not here.
  final bool allowMixedTypes;

  /// Whether YouTube's IAMF upload pipeline accepts this profile. YouTube
  /// supports the Simple and Base profiles; the higher profiles are not
  /// accepted. Surfaced as a "Supported by YouTube" tag in the profile pickers.
  bool get supportedByYouTube =>
      this == IamfProfile.simple || this == IamfProfile.base;

  /// Stable JSON identifier; do not rename without a schema migration.
  String get jsonId => name;

  static IamfProfile fromJsonId(String? id) {
    for (final p in IamfProfile.values) {
      if (p.jsonId == id) return p;
    }
    return IamfProfile.base;
  }
}

