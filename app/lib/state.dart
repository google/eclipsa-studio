    profileIndex: 1,
    specVersion: IamfSpecVersion.v1_0,
    maxAudioElements: 2,
    maxChannels: 18,
    maxSubMixesPerMix: 1,
    maxCodecConfigs: 1,
    allowObjectBased: false,
    allowMixedTypes: false,
  ),
  baseEnhanced(
    label: 'Base-Enhanced',
    profileIndex: 2,
    specVersion: IamfSpecVersion.v1_1,
    maxAudioElements: 28,
    maxChannels: 28,
    maxSubMixesPerMix: 1,
    maxCodecConfigs: 1,
    // Object-based audio is not supported until Base-Advanced (profile 3);
    // Base-Enhanced allows only channel- and scene-based elements.
    allowObjectBased: false,
    allowMixedTypes: true,
  ),
  baseAdvanced(
    label: 'Base-Advanced',
    profileIndex: 3,
    specVersion: IamfSpecVersion.v2_0,
    maxAudioElements: 18,
    maxChannels: 18,
    maxSubMixesPerMix: 2,
    maxCodecConfigs: 2,
    allowObjectBased: true,
    allowMixedTypes: true,
