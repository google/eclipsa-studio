// --- IAMF profile limits ---
// These will vary per profile (Simple, Base, Base-Enhanced, etc.).

/// Maximum number of audio elements supported by the engine (hard cap).
/// Individual IAMF profiles impose tighter limits — see [IamfProfile].
const kMaxAudioElements = 28;

/// Maximum total channel count across all elements (hard engine cap).
const kMaxTotalChannels = 28;

/// IAMF spec version a profile complies with.
///
/// Features gate by the spec version a profile complies with, not by
/// profile "rank": 9.1.6 arrived in v1.1.0, while head-locked binaural and
/// the `binaural_filter_profile` field are v2.0.0 additions. Declared
/// oldest → newest so `.index` comparisons (via [atLeast]) read as "at
/// least this version".
enum IamfSpecVersion {
  v1_0('v1.0.0-errata'),
  v1_1('v1.1.0'),
  v2_0('v2.0.0');

  const IamfSpecVersion(this.label);
  final String label;

  /// True when this version is [other] or newer (newer versions are
  /// supersets, so they also satisfy an older requirement).
  bool atLeast(IamfSpecVersion other) => index >= other.index;
}

/// IAMF profile selection for a session. Each profile constrains the
