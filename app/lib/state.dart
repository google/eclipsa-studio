    // videoBackendFromName so it lives in exactly one place; layer only the
    // known-but-unavailable warning on top.
    final restored = videoBackendFromName(name, currentTargetOs());
    if (restored != VideoBackendKind.auto) {
      state = restored;
    } else if (name != VideoBackendKind.auto.name &&
        VideoBackendKind.values.any((k) => k.name == name)) {
      Log.w(
        LogCat.session,
        'Video backend "$name" not available on this platform; using auto',
      );
    }
  }

  void set(VideoBackendKind kind) {
    state = kind;
    AppPreferences.set(AppPreferences.kVideoBackend, kind.name).then(
      (_) {},
      onError: (Object e) => Log.w(
        LogCat.session,
        'Video backend preference not saved; '
        'change applies this session only',
        e,
      ),
    );
  }

  /// Return to the default without writing to disk — for Settings' Reset to
  /// Defaults, which wipes the preferences file separately. This must be an
  /// explicit state set, not a `ref.invalidate`: `main()` overrides the
  /// provider with a startup-seed notifier whose `build()` returns the
  /// launch-time preference, so an invalidate would resurrect the old value
  /// instead of resetting it.
  void resetToDefault() => state = VideoBackendKind.auto;
}

