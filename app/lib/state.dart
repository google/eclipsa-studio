// --- Data models ---

class AudioElement {
  /// True if this is a channel-based element whose declared layout is
  /// Binaural — i.e. the WAV already contains pre-rendered L/R binaural
  /// content. The Mix view locks headphones_rendering_mode to Stereo
  /// (IAMF spec value 0) for these elements. Mode 0 is the canonical
  /// "already binaural, do not spatialize" authoring value; writing it
  /// to the bitstream is correct for any IAMF decoder. In the engine
  /// the element registers with OAR as a *stereo* element (see
  /// renderer/oar_capability.h), and mode 0 is what routes it through
  /// OAR's identity L/R passthrough on the binaural monitoring target
  /// (the retarget in audio_element_renderer.c:186 of the OAR fork —
  /// OBR's kPassthroughStereo path applies only to binaural-*input*
  /// registration, which we don't use). Any other mode re-binauralizes
  /// the already-binaural signal, so the lock keeps both the
  /// monitoring path and the exported bitstream honest (ES-327).
  bool get isChannelBasedBinaural => type == 'Channel' && layout == 'Binaural';

  final int id;
  final String name;
  final String type; // 'Object' | 'Channel' | 'Scene'
  final String layout;
  final String codec;
  final int color; // ARGB int
  final double gain;
  final bool mute;
  final bool solo;
  final String? wavPath;
  final WavInfo? wavInfo;

  /// Monotonically increasing counter bumped each time the WAV file is
  /// replaced. Forces waveform widgets to reload even when the path is
  /// unchanged. Not serialized to JSON.
  final int wavGeneration;

  // Common binaural parameters
  final BinauralProfile binauralProfile;
  final BinauralMode binauralMode;

  // Object-based parameters
  final double azimuth; // -180 to 180 degrees
  final double elevation; // -90 to 90 degrees
  final double distance; // 0 to 1 normalized
  final bool isDual; // false=Mono (1ch), true=Dual (2ch)
  final double spread; // 0 to 180 degrees (dual only)

  // Scene-based parameters
  final int ambisonicsOrder; // 1=1OA(4ch), 2=2OA(9ch), 3=3OA(16ch), 4=4OA(25ch)

  // Pre-mix input channel routing: inputRouting[destCh] = srcCh (-1 = off).
  // `destCh` indexes the element's output (IAMF layout) channels;
  // `srcCh` indexes the WAV file's source channels. null = identity
  // (no remap — engine fast path). Matches the engine's gather
  // convention; see AudioGraph::set_element_routing.
  final List<int>? inputRouting;

  // Pre-mix time offset in milliseconds (positive = delay, negative =
  // advance). PARKED for 0.20: the UI was removed and playback ignores
  // it, pending the keep-or-drop decision on ES-190 (full implementation
  // waits in draft PR ES-303). Kept in the model + session JSON so
  // sessions that stored an offset still round-trip losslessly.
  final double timeOffsetMs;

  AudioElement({
    required this.id,
    required this.name,
    required this.type,
    required this.layout,
    required this.codec,
    required this.color,
    this.gain = 0,
    this.mute = false,
    this.solo = false,
    this.wavPath,
    this.wavInfo,
    this.wavGeneration = 0,
    this.binauralProfile = BinauralProfile.ambient,
    this.binauralMode = BinauralMode.worldLocked,
    this.azimuth = 0.0,
    this.elevation = 0.0,
    this.distance = 1.0,
    this.isDual = false,
    this.spread = 60.0,
    this.ambisonicsOrder = 1,
    this.inputRouting,
    this.timeOffsetMs = 0,
  });

  /// This element's config as a `'Type · Subtype'` label, matching the
  /// `label` field of [validConfigsForChannelCount] entries so pickers can
  /// locate the current config in a config list by string comparison.
  String get configLabel {
    switch (type) {
      case 'Object':
        return isDual ? 'Object · Dual' : 'Object · Mono';
      case 'Scene':
        return 'Scene · ${ambisonicsOrder}OA';
      default:
        return 'Channel · $layout';
    }
  }

  AudioElement copyWith({
    String? name,
    String? type,
    String? layout,
    int? color,
    double? gain,
    bool? mute,
    bool? solo,
    String? wavPath,
    WavInfo? wavInfo,
    int? wavGeneration,
    BinauralProfile? binauralProfile,
    BinauralMode? binauralMode,
    double? azimuth,
    double? elevation,
    double? distance,
    bool? isDual,
    double? spread,
    int? ambisonicsOrder,
    List<int>? inputRouting,
    bool clearInputRouting = false,
    double? timeOffsetMs,
  }) {
    return AudioElement(
      id: id,
      name: name ?? this.name,
      type: type ?? this.type,
      layout: layout ?? this.layout,
      codec: codec,
      color: color ?? this.color,
      gain: gain ?? this.gain,
      mute: mute ?? this.mute,
      solo: solo ?? this.solo,
      wavPath: wavPath ?? this.wavPath,
      wavInfo: wavInfo ?? this.wavInfo,
      wavGeneration: wavGeneration ?? this.wavGeneration,
      binauralProfile: binauralProfile ?? this.binauralProfile,
      binauralMode: binauralMode ?? this.binauralMode,
      azimuth: azimuth ?? this.azimuth,
      elevation: elevation ?? this.elevation,
      distance: distance ?? this.distance,
      isDual: isDual ?? this.isDual,
      spread: spread ?? this.spread,
      ambisonicsOrder: ambisonicsOrder ?? this.ambisonicsOrder,
      inputRouting: clearInputRouting
          ? null
          : (inputRouting ?? this.inputRouting),
      timeOffsetMs: timeOffsetMs ?? this.timeOffsetMs,
    );
  }
}

