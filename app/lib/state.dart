enum SoundSystem {
  stereo('Stereo', '0+2+0'),
  mono('Mono', '0+1+0'),
  surround5_1('5.1', '0+5+0'),
  surround5_1_2('5.1.2', '2+5+0'),
  surround5_1_4('5.1.4', '4+5+0'),
  surround7_1('7.1', '0+7+0'),
  surround7_1_2('7.1.2', '2+7+0'),
  surround7_1_4('7.1.4', '4+7+0'),
  surround3_1_2('3.1.2', '2+3+0'),
  surround9_1_6('9.1.6', '6+9+0'),
  surround7_1_5_4('7.1.5.4', '5+7+4'),
  surround10_2_9_3('10.2.9.3', '9+10+3'),
  binaural('Binaural', 'Binaural');

  const SoundSystem(this.label, this.ituNotation);

  /// Canonical spelling — the single identifier for this layout. Doubles as
  /// a lookup key ([LoudspeakerLayout.fromDisplayName], the ADM importer's
  /// engine layout name), so it must stay free of decoration. Use [uiLabel]
  /// for anything a user reads.
  final String label;
  final String ituNotation;

  /// [label] plus, where a layout is widely known under a second name, that
  /// name in parentheses. Display only — never compare or persist this.
  String get uiLabel =>
      this == SoundSystem.surround10_2_9_3 ? '10.2.9.3 (22.2)' : label;
}

