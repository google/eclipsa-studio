class MixesNotifier extends Notifier<List<Mix>> {
  @override
  List<Mix> build() => [
    const Mix(id: 1, name: 'Main Mix', language: 'en', subMixes: [SubMix()]),
  ];
  void set(List<Mix> v) {
    if (!assertCreatorMode(ref, op: 'mixes.set')) return;
    state = v;
  }

  void updateMix(int mixId, Mix Function(Mix) updater) {
    if (!assertCreatorMode(ref, op: 'mixes.updateMix')) return;
    state = [
      for (final m in state)
        if (m.id == mixId) updater(m) else m,
    ];
  }

  void addMix(Mix mix) {
    if (!assertCreatorMode(ref, op: 'mixes.addMix')) return;
    state = [...state, mix];
  }

  /// Create a new mix pre-seeded with one sub-mix and default
  /// [MixElementSettings] for each element. Returns the new mix's
  /// list index so the caller can set it active. Active-index
  /// bookkeeping stays with the caller so this notifier doesn't
  /// depend on [activeMixProvider] / [activeSubMixProvider].
  int createDefaultMix(List<AudioElement> elements) {
    if (!assertCreatorMode(ref, op: 'mixes.createDefaultMix')) {
      return -1;
    }
    final id = nextId();
    addMix(
      Mix(
        id: id,
        name: 'Mix $id',
        language: 'en',
        subMixes: [
          SubMix(
            elementSettings: elements
                .map((e) => MixElementSettings(elementId: e.id))
                .toList(),
          ),
        ],
      ),
    );
    return state.length - 1;
  }

  void removeMix(int mixId) {
    if (!assertCreatorMode(ref, op: 'mixes.removeMix')) return;
    state = state.where((m) => m.id != mixId).toList();
  }

  /// Move the mix at [oldIndex] to [newIndex] (both positions in the
  /// current, pre-move list). Contract: the moved mix's FINAL index is
  /// [newIndex] in both directions — it takes the drop target's
  /// original position and everything between shifts by one, so
  /// dropping onto an adjacent neighbor swaps them. (This differs from
  /// [ElementsNotifier.reorder], whose newIndex is a
  /// ReorderableListView gap index with the framework pre-adjustment.)
  /// Order is author-meaningful — it is the tab order, the top-bar
  /// selector order, and the exported IAMF presentation order.
  /// Active-index bookkeeping stays with the caller (as with
  /// [createDefaultMix]): remap [activeMixProvider] so the same mix
  /// stays selected after the move.
  void reorderMix(int oldIndex, int newIndex) {
    if (!assertCreatorMode(ref, op: 'mixes.reorderMix')) return;
    if (oldIndex < 0 || oldIndex >= state.length) return;
    final clamped = newIndex.clamp(0, state.length - 1);
    if (clamped == oldIndex) return;
    final list = [...state];
    final moved = list.removeAt(oldIndex);
    list.insert(clamped, moved);
    state = list;
  }

  /// Remove all settings for [elementId] from every sub-mix in
  /// every mix. Called when an element is deleted.
  void removeElementSettings(int elementId) {
    if (!assertCreatorMode(ref, op: 'mixes.removeElementSettings')) {
      return;
    }
    state = [
      for (final m in state)
        m.copyWith(
          subMixes: [
            for (final sub in m.subMixes)
              sub.copyWith(
                elementSettings: sub.elementSettings
                    .where((s) => s.elementId != elementId)
                    .toList(),
              ),
          ],
        ),
    ];
  }

  /// Ensure every sub-mix in every mix has [MixElementSettings] for
  /// [elementId]. Called when a new element is added so the mix
  /// references it on export — without this, the IAMF textproto's
  /// `sub_mixes.audio_elements` list is empty and iamf-tools rejects
  /// the encode with "Expected at least one sample rate and bit depth".
  void ensureElementSettings(int elementId) {
    if (!assertCreatorMode(ref, op: 'mixes.ensureElementSettings')) {
      return;
    }
    state = [
      for (final m in state)
        m.copyWith(
          subMixes: [
            for (final sub in m.subMixes)
              sub.elementSettings.any((s) => s.elementId == elementId)
                  ? sub
                  : sub.copyWith(
                      elementSettings: [
                        ...sub.elementSettings,
                        MixElementSettings(elementId: elementId),
                      ],
                    ),
          ],
        ),
    ];
  }

  /// Generate next unique ID.
  int nextId() {
    if (state.isEmpty) return 1;
    return state.map((m) => m.id).reduce((a, b) => a > b ? a : b) + 1;
  }
}

