/// Schema for the generated component index.
///
/// Hand-written, like `theme_data.dart` beside `theme_tokens.dart`:
/// `scripts/gen_component_index.py` parses this file's constructors and
/// requires an exact field match, so the schema and the generated data
/// cannot drift apart in either direction.
library;

/// One widget in the gallery header: what it is, and where it is used.
///
/// [usedIn] and [useCount] are generated by scanning `app/lib/`, so they
/// cannot drift from the code. Everything else comes from
/// `app/design/components.json`.
class ComponentInfo {
  const ComponentInfo({
    required this.name,
    required this.declaredIn,
    required this.summary,
    required this.usedIn,
    required this.useCount,
  });

  /// The Dart class name. This is how to reference it in code.
  final String name;

  /// Path of the file declaring it, relative to `app/`.
  final String declaredIn;

  /// One or two sentences on what it is for.
  final String summary;

  /// Files instantiating it, relative to `app/`, with a per-file count.
  /// Ordered by count then path. Deliberately file-level: line numbers
  /// shift on any edit above a call site, which would make the drift
  /// gate fail constantly for no signal.
  final Map<String, int> usedIn;

  /// Total instantiation sites across [usedIn].
  final int useCount;
}
