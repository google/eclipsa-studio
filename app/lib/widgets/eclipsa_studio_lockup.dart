import 'package:flutter/material.dart';
import 'package:flutter_riverpod/flutter_riverpod.dart';

import '../state.dart';
import '../theme.dart';
import 'eclipsa_studio_mark.dart';
import 'eclipsa_studio_wordmark.dart';

/// The mark beside the wordmark, spaced as the brand lockup is.
///
/// The brand lockup (`app/design/brand/eclipsa-studio-lockup.svg`, generated by
/// `scripts/gen_app_icon.py`) sets three things, and this widget sets
/// the same three from [fontSize]:
///
/// - the mark's box is the type size over [kTypeRatio], so the
///   landing's 42 px of type gives an 82 px mark and `fontTitle` 16 a
///   31 px one;
/// - the gap is [kGap] of the mark's box, measured from the cube's
///   silhouette ([markSilhouette]), not from the box the cells stop
///   short of;
/// - the wordmark's cap-height band is centred on the silhouette. The
///   baseline comes from the wordmark's face, Inter, through a
///   [TextPainter], and the cap height is Inter's [kCapHeight].
///
/// [EclipsaStudioWordmark] is one drawing in every theme. The release-stage
/// label is not part of the lockup: it is drawn after the aligned
/// pair, offset from the wordmark as it is beside a wordmark alone.
/// Drawn on the landing screen at 42 px of type and in the top bar at
/// `fontTitle`.
///
/// Watches theme + font mode so it tracks both even when constructed
/// `const` upstream, where no parent rebuild reaches it.
class EclipsaStudioLockup extends ConsumerWidget {
  const EclipsaStudioLockup({
    super.key,
    this.fontSize,
    this.labelFontSize,
    this.onChrome = false,
  });

  /// Type size over mark size, as the brand lockup's
  /// `LOCKUP_TYPE_RATIO`.
  static const double kTypeRatio = 0.515;

  /// Gap from the cube's silhouette to the type, as a fraction of the
  /// mark's box: 20 units of 58.
  static const double kGap = 20 / 58;

  /// Inter's cap height, 1490 of 2048 units per em.
  static const double kCapHeight = 1490 / 2048;

  /// The wordmark's type size; `fontTitle` when null, as the wordmark
  /// itself defaults.
  final double? fontSize;

  /// The release-stage label's size; half the type size when null.
  final double? labelFontSize;

  /// Passed through to [EclipsaStudioMark].
  final bool onChrome;

  /// The mark's box for a wordmark at [fontSize].
  static double markSizeFor(double fontSize) => fontSize / kTypeRatio;

  @override
  Widget build(BuildContext context, WidgetRef ref) {
    ref.watch(themeModeProvider);
    ref.watch(fontSizeModeProvider);

    final size = fontSize ?? T.fontTitle;
    final markSize = markSizeFor(size);
    final silhouette = markSilhouette(markSize);
    final gap = kGap * markSize - (markSize - silhouette.right);

    // Where the wordmark's baseline falls below its top, in the
    // wordmark's face.
    final painter = TextPainter(
      text: TextSpan(
        text: 'x',
        style: TextStyle(
          fontSize: size,
          fontFamily: EclipsaStudioWordmark.family,
        ),
      ),
      textDirection: TextDirection.ltr,
    )..layout();
    final baseline = painter.computeDistanceToActualBaseline(
      TextBaseline.alphabetic,
    );
    painter.dispose();
    final capCentre = baseline - size * kCapHeight / 2;

    // Positive: the type sits lower than the mark's centre and the
    // mark is padded down; negative: the type is.
    final shift = silhouette.center.dy - capCentre;
    final textTop = shift > 0 ? shift : 0.0;
    return Row(
      mainAxisSize: MainAxisSize.min,
      crossAxisAlignment: CrossAxisAlignment.start,
      children: [
        Padding(
          padding: EdgeInsets.only(top: shift < 0 ? -shift : 0),
          child: EclipsaStudioMark(size: markSize, onChrome: onChrome),
        ),
        SizedBox(width: gap),
        Padding(
          padding: EdgeInsets.only(top: textTop),
          child: EclipsaStudioWordmark(
            fontSize: size,
            showLabel: false,
            onChrome: onChrome,
          ),
        ),
        // The release-stage label is not part of the lockup; it
        // follows the pair, offset from the wordmark as it is beside
        // a wordmark drawn alone.
        Padding(
          padding: EdgeInsets.only(top: textTop),
          child: ReleaseStageLabel(
            wordmarkFontSize: size,
            fontSize: labelFontSize,
            onChrome: onChrome,
          ),
        ),
      ],
    );
  }
}
