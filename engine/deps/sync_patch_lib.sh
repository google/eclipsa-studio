# Shared by engine/renderer/sync-oar.sh and engine/iamf/sync-iamf-tools.sh,
# the scripts that regenerate the patches MODULE.bazel applies to the public
# upstreams. Sourced, not run. The caller sets UPSTREAM (the public upstream
# git URL), PIN (the commit constant in MODULE.bazel) and GENERATOR (the
# caller's path in the repo, for the patch header), then calls the
# functions below in order.

set -euo pipefail

ENGINE_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
MODULE="$ENGINE_DIR/MODULE.bazel"

# Pin the diff format so the patches do not depend on the operator's git
# config: diff.noprefix or diff.mnemonicPrefix would break patch_strip = 1,
# and diff.renames or diff.algorithm would change the hunks. --abbrev=7
# keeps the index hashes at 7 characters unless a prefix is ambiguous; git
# lengthens its default abbreviation as a repository grows, which would
# change every index line.
DIFF_FLAGS=(
  --no-color --no-ext-diff --src-prefix=a/ --dst-prefix=b/ --find-renames
  --diff-algorithm=myers --unified=3 --abbrev=7
)

WORKDIR="$(mktemp -d)"
trap 'rm -rf "$WORKDIR"' EXIT

# sync_args "$@": sets FORK, REF and KEEP_PIN from the command line, or
# prints the usage and exits 2. With --keep-pin the patches are written
# against the current pin rather than the merge base, and MODULE.bazel is
# left unchanged.
sync_args() {
  KEEP_PIN=0
  if [ "${1:-}" = "--keep-pin" ]; then
    KEEP_PIN=1
    shift
  fi
  if [ $# -lt 1 ] || [ $# -gt 2 ] || [[ "$1" == -* ]] ||
    [[ "${2:-}" == -* ]]; then
    echo "Usage: $0 [--keep-pin] <fork-path-or-url> [<ref>]" >&2
    exit 2
  fi
  FORK="$1"
  REF="${2:-main}"
}

# Sets REPO to a clone of the fork (a URL is cloned into WORKDIR; a path is
# used as it is, at its repository root) and FORK_SHA to REF resolved in
# that clone.
resolve_fork() {
  if [ -d "$FORK" ]; then
    REPO="$(git -C "$FORK" rev-parse --show-toplevel)"
  else
    echo "Cloning fork..."
    git clone -q "$FORK" "$WORKDIR/fork"
    REPO="$WORKDIR/fork"
  fi
  FORK_SHA="$(git -C "$REPO" rev-parse --verify "$REF^{commit}")"
}

# Sets OLD_PIN from MODULE.bazel, or exits 1 if the constant is missing.
# Runs before any patch is written so a failure leaves the tree untouched.
read_pin() {
  OLD_PIN="$(sed -nE "s/^$PIN = \"([0-9a-f]{40})\"\$/\1/p" "$MODULE")"
  if [ -z "$OLD_PIN" ]; then
    echo "$PIN not found in $MODULE" >&2
    exit 1
  fi
}

# Fetches upstream main into the fork clone. Sets UPSTREAM_SHA, MERGE_BASE
# (its merge base with FORK_SHA), BASE_SHA (the commit the patches are
# written against: MERGE_BASE, or OLD_PIN with --keep-pin), AHEAD
# (upstream commits after MERGE_BASE) and CARRIED (upstream commits from
# BASE_SHA to MERGE_BASE). With --keep-pin, exits 1 unless OLD_PIN is a
# commit and an ancestor of MERGE_BASE, and so of FORK_SHA: a pin the fork
# does not contain would put a revert of upstream changes into the patch,
# and a pin off upstream main has no upstream range to report.
find_base() {
  echo "Fetching upstream main..."
  git -C "$REPO" fetch -q "$UPSTREAM" main
  UPSTREAM_SHA="$(git -C "$REPO" rev-parse FETCH_HEAD)"
  MERGE_BASE="$(git -C "$REPO" merge-base "$FORK_SHA" "$UPSTREAM_SHA")"
  BASE_SHA="$MERGE_BASE"
  if [ "$KEEP_PIN" = 1 ]; then
    if ! git -C "$REPO" cat-file -e "$OLD_PIN^{commit}" 2>/dev/null; then
      echo "$PIN $OLD_PIN is not a commit in the fork clone" >&2
      exit 1
    fi
    if ! git -C "$REPO" merge-base --is-ancestor "$OLD_PIN" "$MERGE_BASE"
    then
      echo "$PIN $OLD_PIN is not an ancestor of $MERGE_BASE, the merge" \
        "base of $FORK_SHA with upstream main" >&2
      exit 1
    fi
    BASE_SHA="$OLD_PIN"
  fi
  AHEAD="$(git -C "$REPO" rev-list --count "$MERGE_BASE..$UPSTREAM_SHA")"
  CARRIED="$(git -C "$REPO" rev-list --count "$BASE_SHA..$MERGE_BASE")"
}

# write_patch <out> <title> <git diff arguments...>
# Writes the provenance header, then `git diff` with DIFF_FLAGS and the
# given arguments (revisions, options and pathspecs), to <out>. The patch
# is written to WORKDIR first and moved over <out> only when `git diff`
# succeeds, so a failed diff leaves the tracked patch as it was.
write_patch() {
  local out="$1" title="$2"
  shift 2
  local tmp
  tmp="$WORKDIR/$(basename "$out")"
  {
    printf '%s\n' "$title" "Upstream base: $BASE_SHA" \
      "Fork commit:   $FORK_SHA" \
      "Generated by $GENERATOR; do not edit by hand." ""
    git -C "$REPO" diff "${DIFF_FLAGS[@]}" "$@"
  } > "$tmp"
  mv "$tmp" "$out"
  echo "$(basename "$out"): $(grep -c '^diff --git' "$out") files"
}

# report_omitted <patch>: lists the files the fork changed between
# MERGE_BASE and FORK_SHA that <patch> does not carry, so an exclusion or a
# fixed path list never drops a change silently. With --keep-pin it also
# lists, under its own heading, the files upstream changed between the pin
# and MERGE_BASE that <patch> does not carry: the patched tree keeps the
# pin's version of those files, and a carried file that depends on the
# newer version does not build.
report_omitted() {
  local out="$1" carried
  carried="$(sed -nE 's#^diff --git a/.* b/(.*)$#\1#p' "$out" | sort -u)"
  _list_uncarried "Fork changes not carried by $(basename "$out"):" \
    "$MERGE_BASE" "$FORK_SHA" "$carried"
  if [ "$BASE_SHA" != "$MERGE_BASE" ]; then
    _list_uncarried \
      "Upstream changes after $PIN not carried by $(basename "$out"):" \
      "$BASE_SHA" "$MERGE_BASE" "$carried"
  fi
}

# _list_uncarried <heading> <from> <to> <carried>: prints <heading> and the
# files changed between <from> and <to> that are not in the newline-
# separated <carried> list, or nothing when there are none.
_list_uncarried() {
  local heading="$1" from="$2" to="$3" carried="$4" missing
  missing="$(comm -23 \
    <(git -C "$REPO" diff --name-only --find-renames "$from" "$to" | sort) \
    <(printf '%s\n' "$carried"))"
  if [ -n "$missing" ]; then
    echo "$heading"
    while IFS= read -r f; do echo "  $f"; done <<<"$missing"
  fi
}

# Sets PIN in MODULE.bazel to BASE_SHA, unless --keep-pin was given, and
# prints the summary.
update_pin() {
  echo
  echo "Fork commit:   $FORK_SHA"
  if [ "$KEEP_PIN" = 1 ]; then
    echo "Upstream base: $BASE_SHA ($PIN, unchanged with --keep-pin)"
    echo "Merge base:    $MERGE_BASE (upstream main is $AHEAD commits ahead)"
    echo "Upstream commits from $PIN to the merge base: $CARRIED"
    return
  fi
  echo "Upstream base: $BASE_SHA (upstream main is $AHEAD commits ahead)"
  sed -i.bak -E "s/^$PIN = \"[0-9a-f]{40}\"\$/$PIN = \"$BASE_SHA\"/" "$MODULE"
  rm -f "$MODULE.bak"
  echo "$PIN: $OLD_PIN -> $BASE_SHA"
}
